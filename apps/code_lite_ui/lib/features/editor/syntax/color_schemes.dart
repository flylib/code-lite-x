import 'package:flutter/painting.dart';

import 'tokenizer.dart';

/// 编辑区配色:代码区背景、默认文字、行号、选区、光标、缩进参考线,以及每类 token 的样式。
/// IDE 外框(标签栏、工具窗)仍是 Darcula;这里只换代码区。
class EditorColorScheme {
  EditorColorScheme({
    required this.id,
    required this.name,
    required this.background,
    required this.foreground,
    required this.lineNumber,
    required this.selection,
    required this.caret,
    required this.indentGuide,
    required Color keyword,
    required Color string,
    required Color number,
    required Color comment,
    required Color function,
    required Color type,
    required Color annotation,
    required Color constant,
    required Color variable,
    required Color tag,
    required Color attribute,
    Color? field,
    Color? builtin,
    Color? docComment,
    Color? link,
    Color? entity,
    Color? codeSpan,
    bool italicComments = true,
    bool italicTypes = false,
  }) : _styles = {
          TokenKind.keyword: TextStyle(color: keyword),
          TokenKind.constant: TextStyle(color: constant),
          TokenKind.type: TextStyle(color: type, fontStyle: italicTypes ? FontStyle.italic : null),
          TokenKind.field: TextStyle(color: field ?? variable, fontStyle: FontStyle.italic),
          TokenKind.builtin: TextStyle(color: builtin ?? function),
          TokenKind.function: TextStyle(color: function),
          TokenKind.string: TextStyle(color: string),
          TokenKind.attrValue: TextStyle(color: string),
          TokenKind.number: TextStyle(color: number),
          TokenKind.comment: TextStyle(color: comment, fontStyle: italicComments ? FontStyle.italic : null),
          TokenKind.quote: TextStyle(color: comment, fontStyle: FontStyle.italic),
          TokenKind.docComment: TextStyle(color: docComment ?? comment, fontStyle: italicComments ? FontStyle.italic : null),
          TokenKind.annotation: TextStyle(color: annotation),
          TokenKind.variable: TextStyle(color: variable),
          TokenKind.tag: TextStyle(color: tag),
          TokenKind.attribute: TextStyle(color: attribute),
          TokenKind.entity: TextStyle(color: entity ?? constant),
          TokenKind.heading: TextStyle(color: keyword, fontWeight: FontWeight.bold),
          TokenKind.bold: const TextStyle(fontWeight: FontWeight.bold),
          TokenKind.italic: const TextStyle(fontStyle: FontStyle.italic),
          TokenKind.link: TextStyle(color: link ?? function),
          TokenKind.codeSpan: TextStyle(color: codeSpan ?? string),
          TokenKind.listMarker: TextStyle(color: keyword),
          TokenKind.key: TextStyle(color: keyword),
          TokenKind.section: TextStyle(color: keyword),
        };

  final String id;
  final String name;
  final Color background;
  final Color foreground;
  final Color lineNumber;
  final Color selection;
  final Color caret;
  final Color indentGuide;
  final Map<TokenKind, TextStyle> _styles;

  /// 该类 token 的样式;普通文字、标点为 null(用 [foreground])。
  TextStyle? styleOf(TokenKind kind) => _styles[kind];
}

