use anyhow::{Context, Result};
use serde::Deserialize;
use std::fs;
use std::path::PathBuf;

#[derive(Debug, Deserialize)]
struct ApiSpec {
    #[allow(dead_code)]
    schema: SchemaInfo,
    #[serde(default)]
    types: Vec<TypeDef>,
    #[serde(default)]
    methods: Vec<MethodDef>,
}

#[derive(Debug, Deserialize)]
struct SchemaInfo {
    #[allow(dead_code)]
    version: String,
    #[allow(dead_code)]
    title: String,
}

#[derive(Debug, Deserialize)]
struct TypeDef {
    name: String,
    #[serde(default)]
    description: String,
    fields: Vec<FieldDef>,
}

#[derive(Debug, Deserialize)]
struct FieldDef {
    name: String,
    #[serde(rename = "type")]
    field_type: String,
}

#[derive(Debug, Deserialize)]
struct MethodDef {
    name: String,
    #[serde(default)]
    description: String,
    handler: String,
    #[serde(default)]
    params: Vec<FieldDef>,
    returns: String,
    #[serde(default)]
    streaming: bool,
}

fn to_pascal_case(s: &str) -> String {
    let mut result = String::new();
    let mut capitalize = true;
    for c in s.chars() {
        if c == '.' || c == '_' || c == '-' {
            capitalize = true;
        } else if capitalize {
            result.push(c.to_ascii_uppercase());
            capitalize = false;
        } else {
            result.push(c);
        }
    }
    result
}

fn to_camel_case(s: &str) -> String {
    let pascal = to_pascal_case(s);
    let mut chars = pascal.chars();
    match chars.next() {
        None => String::new(),
        Some(first) => first.to_ascii_lowercase().to_string() + chars.as_str(),
    }
}

fn rust_type(field_type: &str) -> String {
    if field_type == "string" {
        "String".to_string()
    } else if field_type == "int" {
        "i64".to_string()
    } else if field_type == "bool" {
        "bool".to_string()
    } else if field_type == "float" {
        "f64".to_string()
    } else if field_type.starts_with("list[") && field_type.ends_with(']') {
        let inner = &field_type[5..field_type.len() - 1];
        format!("Vec<{}>", rust_type(inner))
    } else {
        field_type.to_string()
    }
}

fn dart_type(field_type: &str) -> String {
    if field_type == "string" {
        "String".to_string()
    } else if field_type == "int" {
        "int".to_string()
    } else if field_type == "bool" {
        "bool".to_string()
    } else if field_type == "float" {
        "double".to_string()
    } else if field_type.starts_with("list[") && field_type.ends_with(']') {
        let inner = &field_type[5..field_type.len() - 1];
        format!("List<{}>", dart_type(inner))
    } else {
        field_type.to_string()
    }
}

fn generate_rust_types(spec: &ApiSpec) -> String {
    let mut out = String::new();
    out.push_str("// Auto-generated by xtask codegen. DO NOT EDIT.\n");
    out.push_str("#![allow(clippy::all, unused_imports)]\n\n");
    out.push_str("use serde::{Deserialize, Serialize};\n\n");

    // 1. Defined types
    for t in &spec.types {
        if !t.description.is_empty() {
            out.push_str(&format!("/// {}\n", t.description));
        }
        out.push_str("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]\n");
        out.push_str(&format!("pub struct {} {{\n", t.name));
        for f in &t.fields {
            out.push_str(&format!("    pub {}: {},\n", f.name, rust_type(&f.field_type)));
        }
        out.push_str("}\n\n");
    }

    // 2. Method parameter types
    for m in &spec.methods {
        let param_struct = format!("{}Params", to_pascal_case(&m.name));
        out.push_str(&format!("/// Request parameters for `{}`\n", m.name));
        out.push_str("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]\n");
        out.push_str(&format!("pub struct {} {{\n", param_struct));
        for p in &m.params {
            out.push_str(&format!("    pub {}: {},\n", p.name, rust_type(&p.field_type)));
        }
        out.push_str("}\n\n");
    }

    out
}

fn generate_rust_dispatch(spec: &ApiSpec) -> String {
    let mut out = String::new();
    out.push_str("// Auto-generated by xtask codegen. DO NOT EDIT.\n");
    out.push_str("#![allow(clippy::all, unused_imports)]\n\n");
    out.push_str("use code_lite_rpc::protocol::{error_codes, JsonRpcRequest, JsonRpcResponse};\n");
    out.push_str("use crate::CodeLiteContext;\n");
    out.push_str("use super::types::*;\n\n");

    out.push_str("/// Dispatches an incoming JSON-RPC request to the appropriate handler.\n");
    out.push_str("pub fn dispatch_rpc(ctx: *mut CodeLiteContext, req: &JsonRpcRequest) -> JsonRpcResponse {\n");
    out.push_str("    match req.method.as_str() {\n");

    for m in &spec.methods {
        let param_struct = format!("{}Params", to_pascal_case(&m.name));
        out.push_str(&format!("        {:?} => {{\n", m.name));
        if m.params.is_empty() {
            out.push_str(&format!(
                "            match {}(ctx, {}::default()) {{\n",
                m.handler, param_struct
            ));
        } else {
            out.push_str(&format!(
                "            let params: {} = match req.params.as_ref() {{\n",
                param_struct
            ));
            out.push_str("                Some(val) => match serde_json::from_value(val.clone()) {\n");
            out.push_str("                    Ok(p) => p,\n");
            out.push_str("                    Err(e) => return JsonRpcResponse::err(req.id, error_codes::INVALID_PARAMS, e.to_string()),\n");
            out.push_str("                },\n");
            out.push_str("                None => return JsonRpcResponse::err(req.id, error_codes::INVALID_PARAMS, \"Missing required params\"),\n");
            out.push_str("            };\n");
            out.push_str(&format!("            match {}(ctx, params) {{\n", m.handler));
        }
        out.push_str("                Ok(res) => JsonRpcResponse::success(req.id, serde_json::to_value(res).unwrap()),\n");
        out.push_str("                Err(err) => JsonRpcResponse::err(req.id, error_codes::SERVER_ERROR, err),\n");
        out.push_str("            }\n");
        out.push_str("        }\n");
    }

    out.push_str("        _ => JsonRpcResponse::err(\n");
    out.push_str("            req.id,\n");
    out.push_str("            error_codes::METHOD_NOT_FOUND,\n");
    out.push_str("            format!(\"Method not found: {}\", req.method),\n");
    out.push_str("        ),\n");
    out.push_str("    }\n");
    out.push_str("}\n");

    out
}

