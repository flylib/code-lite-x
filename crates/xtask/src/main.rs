fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    let cmd = args.get(1).map(|s| s.as_str()).unwrap_or("codegen");

    if cmd != "codegen" {
        eprintln!("Usage: cargo run -p xtask -- codegen");
        std::process::exit(1);
    }

    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let workspace_root = manifest_dir
        .parent()
        .context("Missing crates dir")?
        .parent()
        .context("Missing workspace root")?;

    let toml_path = workspace_root.join("core_api.toml");
    println!("Reading IDL spec from {}", toml_path.display());
    let toml_content = fs::read_to_string(&toml_path)
        .with_context(|| format!("Failed to read {}", toml_path.display()))?;

    let spec: ApiSpec = toml::from_str(&toml_content)
        .with_context(|| "Failed to parse core_api.toml")?;

    println!(
        "Parsed IDL: {} types, {} methods",
        spec.types.len(),
        spec.methods.len()
    );

    // 1. Rust Output
    let rust_gen_dir = workspace_root.join("crates/code-lite-ffi/src/generated");
    fs::create_dir_all(&rust_gen_dir)?;

    let rust_types_content = generate_rust_types(&spec);
    let rust_types_path = rust_gen_dir.join("types.rs");
    fs::write(&rust_types_path, rust_types_content)?;
    println!("Generated Rust types -> {}", rust_types_path.display());

    let rust_dispatch_content = generate_rust_dispatch(&spec);
    let rust_dispatch_path = rust_gen_dir.join("dispatch.rs");
    fs::write(&rust_dispatch_path, rust_dispatch_content)?;
    println!("Generated Rust dispatch -> {}", rust_dispatch_path.display());

    let rust_mod_path = rust_gen_dir.join("mod.rs");
    let rust_mod_content = "// Auto-generated by xtask codegen. DO NOT EDIT.\npub mod types;\npub mod dispatch;\npub use types::*;\npub use dispatch::*;\n";
    fs::write(&rust_mod_path, rust_mod_content)?;
    println!("Generated Rust mod -> {}", rust_mod_path.display());

    // 2. Dart Output
    let dart_gen_dir = workspace_root.join("apps/code_lite_ui/lib/core/api/generated");
    fs::create_dir_all(&dart_gen_dir)?;

    let dart_client_content = generate_dart_client(&spec);
    let dart_client_path = dart_gen_dir.join("core_api_client.dart");
    fs::write(&dart_client_path, dart_client_content)?;
    println!("Generated Dart client -> {}", dart_client_path.display());

    println!("xtask codegen completed successfully!");
    Ok(())
}
